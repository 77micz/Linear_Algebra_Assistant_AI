# ------------------------ 函数 ------------------------


def save_test_set(test_set: list[dict], output_path: str):
    """
    保存测试集到文件
    :param test_set: 测试集
    :param output_path: 输出路径
    :return: None
    """
    # 转为绝对路径
    output_path = os.path.abspath(output_path)
    # 判断路径是否存在
    if not os.path.exists(os.path.dirname(output_path)):
        os.makedirs(os.path.dirname(output_path))

    # 保存测试集到文件
    """
    格式：[
          {
            "id": "LA-001",
            "question": "什么是向量组的极大线性无关组？",
            "question_type": "concept_definition",
            "expected_chunks": ["3.2-定义3.4", "3.2-例3.3"],
            "key_concepts": ["极大线性无关组", "向量组", "线性无关", "秩"],
            "expected_answer_points": [
              "部分组线性无关",
              "原向量组中任一向量可由该部分组线性表示",
              "极大线性无关组所含向量个数 = 向量组的秩"
            ],
            "must_not_include": ["矩阵的秩", "行列式"]
          }
          ...
    ]
    """
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("[")
        f.write("\n")
        for question in test_set:
            # 制表符
            f.write("\t")
            f.write(json.dumps(question, ensure_ascii=False))
            # 判断是否为最后一个元素
            if question != test_set[-1]:
                f.write(",")
            f.write("\n")
        f.write("]")



# ------------------------ 主流程 ------------------------
if __name__ == "__main__":
    save_test_set(test_set, "test_set.json")



























